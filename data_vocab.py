# 合并扩充词库（data_extra.py）
# 单独放一个文件便于日后继续追加；这里做去重合并
# ============================================================
def _merge_words(base, extra):
    seen = {w[0].lower() for w in base}
    out = list(base)
    for w in extra:
        key = w[0].lower()
        if key not in seen:
            seen.add(key)
            out.append(w)
    return out


